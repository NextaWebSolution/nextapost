<?php
// Lists every translatable string: __('…') in PHP and np.t('…') in JS, plus Lang::JS_KEYS.
// Usage: php tools/i18n-extract.php [--json]   (writes lang/_keys.json with --write)
declare(strict_types=1);
$root = dirname(__DIR__);
$keys = [];
$jsKeys = [];
$add = function (string $s, string $where) use (&$keys): void {
    $keys[$s][] = $where;
};
$it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root, FilesystemIterator::SKIP_DOTS));
foreach ($it as $f) {
    $p = $f->getPathname();
    if (preg_match('#/(vendor|node_modules|tests|lang|storage|\.git)/#', $p)) continue;
    $ext = $f->getExtension();
    if ($ext !== 'php' && $ext !== 'js') continue;
    $src = (string) file_get_contents($p);
    $rel = substr($p, strlen($root) + 1);
    if ($ext === 'php' && preg_match_all("/\\b__(?:html)?\\(\\s*'((?:[^'\\\\]|\\\\.)*)'/", $src, $m)) foreach ($m[1] as $s) $add(str_replace("\\'", "'", $s), $rel);
    // np.t('…') appears in .js files and in Alpine attributes inside views; these keys are shipped to the browser.
    if (preg_match_all("/np\\.t\\(\\s*'((?:[^'\\\\]|\\\\.)*)'/", $src, $m)) foreach ($m[1] as $s) { $s = str_replace("\\'", "'", $s); $add($s, $rel); $jsKeys[$s] = true; }
    if ($ext === 'php' && preg_match_all('/\\b__\\(\\s*"((?:[^"\\\\]|\\\\.)*)"/', $src, $m)) foreach ($m[1] as $s) $add($s, $rel);
}
// Keys the layout always sends to the browser (Lang::JS_KEYS).
if (preg_match('/JS_KEYS\s*=\s*\[(.*?)\];/s', (string) file_get_contents($root . '/src/Core/Lang.php'), $m)
    && preg_match_all("/'((?:[^'\\\\]|\\\\.)*)'/", $m[1], $mm)) {
    foreach ($mm[1] as $s) { $s = str_replace("\\'", "'", $s); $add($s, 'src/Core/Lang.php'); $jsKeys[$s] = true; }
}
ksort($keys);
if (in_array('--write', $argv, true)) {
    $js = array_keys($jsKeys);
    sort($js);
    file_put_contents($root . '/lang/_js.php', "<?php\n// Generated by tools/i18n-extract.php --write: strings the browser scripts translate with np.t().\nreturn " . var_export($js, true) . ";\n");
    file_put_contents($root . '/lang/_keys.json', json_encode(array_keys($keys), JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) . "\n");
}
$words = array_sum(array_map(fn ($k) => str_word_count($k), array_keys($keys)));
fwrite(STDERR, count($keys) . " strings, ~$words words\n");
