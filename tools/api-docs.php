$type = function (array $s): string {
    $t = $s['type'] ?? 'any';
    $t = is_array($t) ? implode(' or ', $t) : $t;
    if ($t === 'array' && isset($s['items']['type'])) {
        $t = 'array of ' . (is_array($s['items']['type']) ? implode('/', $s['items']['type']) : $s['items']['type']);
    }
    if (isset($s['enum'])) {
        $t .= ': ' . implode(', ', array_map(fn ($v) => '`' . ($v === null ? 'null' : $v) . '`', $s['enum']));
    }
    if (isset($s['minimum']) || isset($s['maximum'])) {
        $t .= ' (' . ($s['minimum'] ?? '…') . '–' . ($s['maximum'] ?? '…') . ')';
    }
    return $t;
};
